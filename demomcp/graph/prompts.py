def select_system(base: str, intent: str | None) -> str:
    """Tool/RAG 节点的取数引导：基于 domain 提示 + 意图给方向（不点名工具，由模型对照 tool 清单自选）。"""
    hint = {
        "market": "用户要行情/指标。从可用工具中选行情/指标类工具，给足标的与日期（区间）参数，注意复权口径。",
        "report": "用户要财报/财务细节。从可用工具中选财报/财务类工具，给足标的与报告期/期数；可结合财报知识库作答。",
        "compare": "用户要对比分析。可能需要调用一次或多次取数工具，取回可比数据（多标的/多区间），便于对比；可结合财报知识库。",
    }.get(intent or "", "用户要行情/指标。从可用工具中选行情/指标类工具，给足标的与日期参数。")
    return (
        f"{base}\n\n本轮意图：{intent or '未定'}。{hint}\n"
        "只给出必要的一次或多次工具调用，不要重复取相同的数；拿不准可用工具时先确认有哪些可用工具。"
        "参数可用容错形式（公司名/别名/代码、日期多格式或相对词如近一年/今天），系统会自动归一化到 ts_code 与 YYYYMMDD。\n"
        "报告期选择（务必确定唯一）：财报/年报类问题只用**最新已发布年度**的年报期次（如 2024年报 → 20241231）"
        "或最近季度期次（2024Q1 / 2024年报 / 20240931 等容错写法）；区间类用起止日期；不确定时用默认『近两年』。"
    )


def synth_system(base: str, intent: str | None = None) -> str:
    """Synthesizer 节点的总结引导：基于 domain 提示 + 取数证据，要求全面覆盖、层级清晰的 Markdown 输出、可溯源、不编造。"""
    extra = (
        "这是一次对比分析，请明确给出各标的/区间之间的差异（如涨跌幅/估值/财务指标的 delta）。"
        if intent == "compare"
        else ""
    )
    return (
        f"{base}\n\n请聚焦用户的问题，基于下方『可用数据』中与问题相关的全部依据，给出结构清晰、信息完整的回答；"
        f"不要遗漏与问题相关的证据，也不要塞入与问题无关的检索块；{extra}\n\n"
        "【输出格式规范】\n"
        "1. 结构分层：先给一句核心结论；再按逻辑分节展开（用『一、二、三』或 `### ` 小节标题按主题分组，标题不超过三层），"
        "结论→分节→表格→引用→结尾总结，把与问题相关的每一类信息都纳入对应小节。\n"
        "2. 表格化：凡是一组结构性、可比较的数据（多期趋势、多标的对比、多指标快照），必须用 Markdown 表格呈现，"
        "首行为表头（如 `| 指标 | 本期 | 上期 | 变动 |`），数字保留单位（% / 亿元 / 倍）并对齐；"
        "不同主题分表呈现，信息宁可多一节也不省略。\n"
        "3. 关键强调：关键数字、日期、百分比（如 1604.9 元、2024-12-31、12.3%）用 `**加粗**` 标记强调，"
        "让读者一眼看到重点；表格内的要点数据也可加粗表头或关键行。\n"
        "4. 直接引用：引用年报/报告原文时用引号；页码、章节等定位信息交由界面『查看引用来源』展示，正文不重复列出。\n"
        "5. 边界：仅当数据天然成表时用表格；单个数值或简单叙述用正文段落；不要为了凑表格而造表。\n\n"
        "始终遵循：\n"
        "- 与问题相关的证据务必全部覆盖，不得压缩、省略或只挑部分；与问题无关的内容一律不写。\n"
        "- **正文不要出现任何来源的详细信息**（公司名、年份、页码、章节、报告标题、工具名、接口名都不写）；"
        "来源信息由界面统一展示，正文只写结论与分析，**正文不要加来源编号**。\n"
        "- 结尾请加一段『核心策略 / 结论总结』，把要点归纳成几句。\n"
        "- 不编造、不假设工具结果里没有的数据；若数据不足以回答，如实说明。"
    )
