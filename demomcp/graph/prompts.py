"""五节点状态机的系统提示词（工具无关，具体工具由 ToolProvider::list_tools 提供）。

设计依据（Role-Task-Context 框架 + 投研机构分工映射）：把五节点管线对应成一条 **AI 驱动的投研工作流**——
router 是问题分诊台（先判断任务类型，不做分析）；rewrite_query 是检索工程角色（把口语提问改写成
契合年报检索的子句）；tool_rag 是数据尽调分析师（Data-CoT：对齐标的/口径/期次、自检取回的数据）；
synthesizer 是分析主笔（Concept-CoT + Thesis-CoT：把尽调阶段的证据按**卖方研报的行业标准骨架**
组织成结论先行、可溯源、不编造的投研输出）。

三反编造纪律（贯穿取数与合成）：评级用**方向性判断**而非硬凑买卖评级；目标价只在与证据强度匹配时才给，
否则明确『暂无可靠目标价』；盈利预测/估值等数字表取到真实数据才填，取不到标『数据未接入』，绝不硬造。

Router 用严格 JSON 提示做意图分类 + 报告 skill 命中；Tool/RAG 与 Synthesizer 在「domain 基础提示」
（settings.system_prompt）之上叠加各自的任务引导，从而让编排器尊重上层语义工具层/标的约束，不改即插即用。
"""

from __future__ import annotations

from datetime import datetime, timedelta, timezone

# 基础 router 文案：意图分类 + skill 字段（skill 由 skills.build_router_system 视注册表拼接命中清单）。

_BEIJING = timezone(timedelta(hours=8))


def today_context() -> str:
    """当前日期锚点（北京时间，A 股交易日历所在时区），供 LLM 换算「最近30日/近一年/今天」等相对时间。

    每次调用现取 datetime.now()（不在图构建期打包进闭包），避免 CLI 长驻会话里日期被固化后逐渐过期。
    不用 zoneinfo：Windows 默认不带 IANA 时区数据库，需另装 tzdata 才能解析 "Asia/Shanghai"；
    固定 UTC+8 偏移更稳——中国不实行夏令时，这个偏移常年不变。
    """
    today = datetime.now(_BEIJING).date().isoformat()
    return (
        f"【当前时间】今天的实际日期是 {today}（北京时间）。"
        "所有「最近/近N日/近N年/今天/昨天/去年/上季度」等相对时间表达都以这个日期为基准换算，"
        "不要使用你自身训练知识里的默认时间。"
    )

